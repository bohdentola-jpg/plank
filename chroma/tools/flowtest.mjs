// End-to-end UI flow: title -> creator -> plaza -> tower lobby -> battle.
import { createServer } from 'node:http';
import { readFile, mkdir } from 'node:fs/promises';
import { extname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const { chromium } = createRequire(import.meta.url)('playwright');
const root = fileURLToPath(new URL('../..', import.meta.url));
const qa = fileURLToPath(new URL('../qa/', import.meta.url));
await mkdir(qa, { recursive: true });
const MIME = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css' };
const server = createServer(async (req, res) => { try { let p = decodeURIComponent(req.url.split('?')[0]); if (p.endsWith('/')) p += 'index.html'; res.writeHead(200, { 'content-type': MIME[extname(p)] || 'application/octet-stream' }); res.end(await readFile(join(root, p))); } catch { res.writeHead(404); res.end(); } });
await new Promise((r) => server.listen(0, r));
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport: { width: 1100, height: 620 } });
const errors = [];
page.on('pageerror', (e) => { errors.push(e.message); console.log('[pageerror]', e.message); });
page.on('console', (m) => { if (m.type() === 'error') console.log('[console]', m.text().slice(0, 300)); });
const ready = () => page.waitForFunction(() => window.__chroma?.mode && !window.__chroma.loadingNow, null, { timeout: 180000 });
const step = (s) => console.log('--', s);
await page.goto(`http://127.0.0.1:${server.address().port}/chroma/index.html?qa&nonews`);
await page.evaluate(() => localStorage.clear());
await page.reload();
await ready();
await page.waitForTimeout(1500);
step('title'); await page.keyboard.press('Enter'); await page.waitForTimeout(600);
await page.click('.title-menu [data-a="plaza"]'); await page.waitForTimeout(1500);
step('creator'); await page.fill('.name-in', 'Splashy');
await page.click('.locker [data-key="crest"] [data-v="fan"]');
await page.click('.locker [data-key="ink"] .swatch:nth-child(4)');
await page.waitForTimeout(4000);
await page.screenshot({ path: join(qa, 'flow_creator.png') });
await page.click('.locker [data-back]'); await page.waitForTimeout(800);
const prof = await page.evaluate(() => ({ name: window.__chroma.profile.name, crest: window.__chroma.profile.look.crest, ink: window.__chroma.profile.ink, created: window.__chroma.profile.created }));
step('profile ' + JSON.stringify(prof));
// PLAY now wakes you up at home: grab a weapon and head out the front door
step('house -> plaza');
await page.evaluate(() => { const m = window.__chroma.mode; if (m.constructor.name === 'House') { m.setHeld(window.__chroma.profile.owned[0]); m.leave(); } });
await page.waitForFunction(() => window.__chroma.mode?.constructor.name === 'Plaza' && !window.__chroma.loadingNow, null, { timeout: 180000 });
await page.waitForTimeout(1500);
step('walk to tower');
await page.evaluate(() => { const m = window.__chroma.mode, p = m.player; p.place(p.pos.clone().set(0, 0.3, -30.5), Math.PI); m.rig.yaw = Math.PI; });
await page.waitForTimeout(1500);
console.log('state', await page.evaluate(() => { const m = window.__chroma.mode; return JSON.stringify({ ui: m.uiOpen, news: m.newsOn, title: m.titleMode, loc: m.location, pos: m.player.pos, near: m.nearest()?.kind, fading: m.fading }); }));
const prompt = await page.evaluate(() => document.getElementById('prompt').innerText);
step('prompt: ' + prompt);
await page.keyboard.press('KeyE'); await page.waitForTimeout(1200);
await page.screenshot({ path: join(qa, 'flow_lobby.png') });
await page.click('.lobby [data-k="hard"]');
await page.click('.lobby [data-st="skyline"]');
await page.click('.lobby [data-a="go"]');
step('matchmaking');
await page.waitForFunction(() => window.__chroma.mode?.constructor.name === 'Battle' && !window.__chroma.loadingNow, null, { timeout: 240000 });
await page.waitForTimeout(3000);
const b = await page.evaluate(() => { const m = window.__chroma.mode; return { kind: m.constructor.name, stage: m.stage?.name, t: m.timeLeft, skill: m.opts?.skill, weapon: m.player?.weapon.id, name: m.player?.name, state: m.state }; });
step('battle ' + JSON.stringify(b));
await page.screenshot({ path: join(qa, 'flow_battle.png') });
console.log('errors:', errors.length);
await browser.close(); server.close(); process.exit(0);
