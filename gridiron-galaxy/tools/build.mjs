// Builds the single-file index.html: dev.html template + styles.css inlined + the whole src/ tree bundled by esbuild.
// Run with `npm run build` (needs `npm install` once). Players never need this: the built index.html is committed.
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
process.chdir(root);
const res = await build({ entryPoints: ['src/main.js'], bundle: true, format: 'iife', target: ['es2020'], write: false, legalComments: 'none', logLevel: 'warning', charset: 'utf8' });
// an inline script must never contain these sequences, or the HTML parser ends the script early
const js = res.outputFiles[0].text.replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--');
const css = readFileSync('styles.css', 'utf8');
let html = readFileSync('dev.html', 'utf8');
if (!html.includes('<!--STYLES-->') || !html.includes('<!--SCRIPT-->')) throw new Error('dev.html is missing the <!--STYLES--> / <!--SCRIPT--> markers');
html = html.replace(/<!--STYLES-->.*$/m, `<style>\n${css}</style>`);
html = html.replace(/<!--SCRIPT-->.*$/m, `<script>\n${js}</script>`);
html = html.replace('<!DOCTYPE html>', '<!DOCTYPE html>\n<!-- GENERATED FILE. Built by tools/build.mjs from dev.html + styles.css + src/. Edit those and run `npm run build`; do not edit this file by hand. -->');
writeFileSync('index.html', html);
console.log(`index.html written: ${(html.length / 1048576).toFixed(2)} MB (${res.warnings.length} esbuild warnings)`);
