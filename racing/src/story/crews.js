// persistent rival: one car (always the same model and livery, so you know
// them on the grid), a driving style, a skill offset, a PR edge, a short bio
// and the line they say before a race. The grid tunes their parts to each
// event's rating; the car and the paint never change.
//
// crew: the chapter id they belong to. skill: added to the chapter's base
// skill (bosses: absolute). edge: added to the event's PR when they're tuned.

