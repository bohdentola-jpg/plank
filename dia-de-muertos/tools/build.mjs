// Builds play-offline.html: the whole game in ONE file (Three.js, code, styles
// and fonts inlined) that opens by double-click — no server, no internet.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { build } from 'esbuild';

const root = fileURLToPath(new URL('..', import.meta.url));
const read = (p) => readFile(join(root, p), 'utf8');

const out = await build({
  entryPoints: [join(root, 'src/main.js')],
  bundle: true,
  format: 'esm',
  minify: true,
  target: 'es2020',
  write: false,
  legalComments: 'none',
  alias: { three: join(root, 'vendor/three.module.js') },
  logLevel: 'warning',
});
let js = out.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');

let css = await read('styles.css');
for (const [file, name] of [['fonts/LilitaOne-latin.woff2', 'LilitaOne'], ['fonts/Nunito-latin.woff2', 'Nunito']]) {
  const b64 = (await readFile(join(root, file))).toString('base64');
  css = css.replace(`url('${file}')`, `url(data:font/woff2;base64,${b64})`);
  void name;
}

let html = await read('index.html');
html = html.replace('<link rel="stylesheet" href="styles.css" />', () => `<style>\n${css}\n</style>`);
html = html.replace(/<script type="importmap">[\s\S]*?<\/script>\n/, '');
html = html.replace('<script type="module" src="src/main.js"></script>', () => `<script type="module">\n${js}\n</script>`);
html = html.replace('<head>', '<head>\n<!-- The Marigold Path — single-file build (generated by tools/build.mjs; edit the files in src/ instead) -->');
await writeFile(join(root, 'play-offline.html'), html);
console.log(`play-offline.html: ${(html.length / 1024 / 1024).toFixed(2)} MB`);
