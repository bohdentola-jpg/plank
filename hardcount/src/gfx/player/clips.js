const DEFAULT_LAG = { neck: 0.03, head: 0.045 };

function compileClip(name, o) {
  const dur = o.dur ?? ACTIONS[name]?.dur ?? o.keys[o.keys.length - 1][0];
  const tracks = compileKeys(o.keys);
  const mask = tracks.mask.slice();
  let legTracks = null;
  if (o.upper) {
    for (let gi = 0; gi < GROUPS.length; gi++) if (!UPPER.includes(GROUPS[gi])) mask[gi] = 0;
    if (o.legs) legTracks = compileKeys(o.legs);
  }
  const lag = new Float32Array(GROUPS.length);
  const L = { ...DEFAULT_LAG, ...(o.lag || {}) };
  for (const [g, v] of Object.entries(L)) if (GI[g] !== undefined) lag[GI[g]] = v;
  const info = ACTIONS[name] || {};
  return {
    name, dur, tracks, mask, legTracks, lag,
    upper: !!o.upper,
    legsLoco: o.legsLoco ?? 0,
    ball: !!o.ball,
    grip: o.grip || null, gripUntil: o.gripUntil ?? dur,
    reach: o.reach || null, reachHands: o.reachHands || 'both',
    look: o.look ?? 1,
    side: o.side || 'R',
    sideFromCarry: !!o.sideFromCarry,
    held: !!info.held, loopFrom: o.loopFrom ?? (info.held ? 0 : null),
    end: info.end || null,
    variant: o.variant || null,
  };
}

export const CLIPS = {};
for (const [name, o] of Object.entries(DEF)) CLIPS[name] = compileClip(name, o);

export const BASES = {};
for (const [name, spec] of Object.entries(BASE_SPECS)) {
  const { pose } = poseOf(spec);
  BASES[name] = { pose, info: BASE_INFO[name] || { upright: 1 } };
}

/** Clip-local time for an action time t (loops held clips). */
export function clipTime(clip, t) {
  if (t <= clip.dur) return Math.max(0, t);
  if (clip.held && clip.loopFrom !== null) {
    const span = clip.dur - clip.loopFrom;
    return clip.loopFrom + ((t - clip.loopFrom) % span);
  }
  return clip.dur;
}

/** Names in the contract that have no clip (should be empty). */
export function missingClips() {
  return Object.keys(ACTIONS).filter((n) => !CLIPS[n]);
}
